//! Menjalankan aturan ACL Tauri yang SEBENARNYA untuk satu pertanyaan:
//! dengan `capabilities/default.json` apa adanya, apakah `mkdir` dan
//! `write_file`/`write_text_file` lolos di `<appLocalData>/projects/...`?
//!
//! Yang dipakai dari crate asli:
//!   * `tauri_utils::acl::resolved::Resolved::resolve` menentukan permission mana
//!     yang memberi perintah dan permission mana yang menyumbang scope. Di sinilah
//!     `resolved.rs:172` menaruh permission yang `commands.allow` DAN `commands.deny`
//!     kosong ke `global_scope`, bukan ke `command_scope`.
//!   * `glob` dengan opsi yang sama seperti `tauri::scope::fs::Scope::new`
//!     (`require_literal_separator: true`), karena itulah pencocok yang dipakai
//!     `is_allowed` di `resolve_path`.
//!
//! Yang ditulis tangan cuma dua hal, dan keduanya bisa diperiksa pembaca:
//!   * penggabungan `global_scope` + `command_scope` yang dilakukan
//!     `tauri-plugin-fs/src/commands.rs` `resolve_path` (baris 1617-1655), dan
//!   * penggantian variabel `$APPLOCALDATA` dst. dengan akar Android.
//!
//! Kalau hasilnya tidak sesuai harapan, alat ini keluar 1. Jadi ia uji, bukan
//! cuma cetakan.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use tauri_utils::acl::capability::Capability;
use tauri_utils::acl::manifest::{Manifest, PermissionFile};
use tauri_utils::acl::resolved::Resolved;
use tauri_utils::acl::Value;
use tauri_utils::platform::Target;

/// Akar direktori privat aplikasi di Android untuk `com.geokebun.app`
/// (`tauri.android.conf.json`). `app_local_data_dir()` di Android mengembalikan
/// `getDataDir()` apa adanya, yaitu `/data/user/0/<paket>/files`, tanpa
/// ditambahi identifier lagi (tauri `path/android.rs:160`).
fn akar() -> Vec<(&'static str, &'static str)> {
    vec![
        ("$APPLOCALDATA", "/data/user/0/com.geokebun.app/files"),
        ("$APPDATA", "/data/user/0/com.geokebun.app/files"),
        ("$APPCONFIG", "/data/user/0/com.geokebun.app/files"),
        ("$APPCACHE", "/data/user/0/com.geokebun.app/cache"),
        ("$APPLOG", "/data/user/0/com.geokebun.app/log"),
        ("$TEMP", "/data/user/0/com.geokebun.app/cache"),
    ]
}

fn bentangkan(pola: &str) -> String {
    let mut keluar = pola.to_string();
    for (var, root) in akar() {
        keluar = keluar.replace(var, root);
    }
    keluar
}

fn jalur_scope(nilai: &[Value]) -> Vec<String> {
    nilai
        .iter()
        .filter_map(|v| match v {
            Value::String(s) => Some(s.clone()),
            Value::Map(m) => m.get("path").and_then(|p| match p {
                Value::String(s) => Some(s.clone()),
                _ => None,
            }),
            _ => None,
        })
        .collect()
}

/// Muat semua berkas permission plugin fs, rekursif: `autogenerated/commands`
/// wajib ikut, kalau tidak `allow-mkdir` tidak ketemu dan resolver panic.
fn muat_manifest(dir: &Path) -> Manifest {
    let mut berkas = Vec::new();
    let mut tumpukan = vec![dir.to_path_buf()];
    while let Some(d) = tumpukan.pop() {
        for entri in fs::read_dir(&d).expect("direktori permissions") {
            let p = entri.unwrap().path();
            if p.is_dir() {
                tumpukan.push(p);
            } else if p.extension().and_then(|e| e.to_str()) == Some("toml") {
                berkas.push(p);
            }
        }
    }
    berkas.sort();
    let isi = berkas
        .into_iter()
        .map(|p| {
            let s = fs::read_to_string(&p).unwrap();
            toml::from_str::<PermissionFile>(&s).unwrap_or_else(|e| panic!("{}: {e}", p.display()))
        })
        .collect();
    Manifest::new(isi, None)
}

/// Pola allow efektif untuk satu perintah. `resolve_path` menggabungkan scope
/// global dengan scope milik perintah itu, jadi dua-duanya dijumlahkan di sini.
fn pola_untuk(resolved: &Resolved, perintah: &str) -> Option<Vec<String>> {
    let kunci = format!("plugin:fs|{perintah}");
    let perintah_izin = resolved.allowed_commands.get(&kunci)?;
    let mut pola: Vec<String> = resolved
        .global_scope
        .get("fs")
        .map(|s| jalur_scope(&s.allow))
        .unwrap_or_default();
    for p in perintah_izin {
        if let Some(id) = p.scope_id {
            if let Some(scope) = resolved.command_scope.get(&id) {
                pola.extend(jalur_scope(&scope.allow));
            }
        }
    }
    Some(pola)
}

fn cocok(pola: &str, jalur: &str) -> bool {
    let opsi = glob::MatchOptions {
        case_sensitive: true,
        require_literal_separator: true,
        require_literal_leading_dot: true,
    };
    glob::Pattern::new(pola)
        .map(|p| p.matches_path_with(Path::new(jalur), opsi))
        .unwrap_or(false)
}

const PERINTAH: [&str; 6] = [
    "mkdir",
    "write_file",
    "write_text_file",
    "read_file",
    "read_dir",
    "remove",
];

/// Empat jalur yang dipakai store bundel: direktori `projects/` sendiri (target
/// `mkdir`), satu direktori proyek, satu berkas di dalamnya, dan satu berkas
/// `startup-projects` sebagai pembanding.
const JALUR: [&str; 4] = [
    "/data/user/0/com.geokebun.app/files/projects",
    "/data/user/0/com.geokebun.app/files/projects/kebun-saya",
    "/data/user/0/com.geokebun.app/files/projects/kebun-saya/project.json",
    "/data/user/0/com.geokebun.app/files/startup-projects/a.json",
];

/// `None` = perintahnya tidak diberikan permission mana pun.
/// `Some(n)` = perintah diberikan, dan `n` dari 4 jalur di atas lolos scope.
type Hasil = BTreeMap<&'static str, Option<usize>>;

fn jalankan(cap: &serde_json::Value, acl: &BTreeMap<String, Manifest>) -> Hasil {
    let capability: Capability =
        serde_json::from_value(cap.clone()).expect("capability tidak bisa dibaca");
    let mut caps = BTreeMap::new();
    caps.insert(capability.identifier.clone(), capability);
    let resolved = Resolved::resolve(acl, caps, Target::Android).expect("acl resolve");

    PERINTAH
        .iter()
        .map(|perintah| {
            let hasil = pola_untuk(&resolved, perintah).map(|pola| {
                let dibentangkan: Vec<String> = pola.iter().map(|p| bentangkan(p)).collect();
                JALUR
                    .iter()
                    .filter(|j| dibentangkan.iter().any(|p| cocok(p, j)))
                    .count()
            });
            (*perintah, hasil)
        })
        .collect()
}

/// Versi crate yang dipakai aplikasi. Kalau `Cargo.lock` memuat versi lain,
/// alat ini berhenti: hasil yang dihitung dari permission set yang berbeda tidak
/// membuktikan apa pun tentang aplikasi yang dikirim.
const VERSI_PLUGIN_FS: &str = "2.7.1";
const VERSI_TAURI_UTILS: &str = "2.10.2";

fn versi_di_lock(isi: &str, nama: &str) -> Option<String> {
    let mut kena = false;
    for baris in isi.lines() {
        let b = baris.trim();
        if b.starts_with("name = ") {
            kena = b == format!("name = \"{nama}\"");
        } else if kena && b.starts_with("version = ") {
            return Some(b.trim_start_matches("version = ").trim_matches('"').to_string());
        }
    }
    None
}

/// Cari direktori `permissions` plugin fs: yang diunduh `siapkan.sh` lebih dulu,
/// lalu cache registry cargo sebagai cadangan.
fn permissions_bawaan() -> Option<PathBuf> {
    let lokal = Path::new(env!("CARGO_MANIFEST_DIR")).join(format!("permissions-fs-{VERSI_PLUGIN_FS}"));
    if lokal.is_dir() {
        return Some(lokal);
    }
    let home = std::env::var("HOME").ok()?;
    let src = PathBuf::from(home).join(".cargo").join("registry").join("src");
    for entri in fs::read_dir(src).ok()? {
        let kandidat = entri.ok()?.path().join(format!("tauri-plugin-fs-{VERSI_PLUGIN_FS}")).join("permissions");
        if kandidat.is_dir() {
            return Some(kandidat);
        }
    }
    None
}

fn main() {
    let mut argumen = std::env::args().skip(1);
    let cap_path = argumen.next().unwrap_or_else(|| {
        // Jalur capability yang diperiksa: yang ada di pohon ini, bukan salinan,
        // supaya uji ini tidak bisa basi terhadap berkas yang sebenarnya dipakai.
        Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../../apps/geolibre-desktop/src-tauri/capabilities/default.json")
            .to_string_lossy()
            .into_owned()
    });
    let lock = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../../apps/geolibre-desktop/src-tauri/Cargo.lock");
    let isi_lock = fs::read_to_string(&lock).expect("baca Cargo.lock aplikasi");
    for (nama, harap) in [("tauri-plugin-fs", VERSI_PLUGIN_FS), ("tauri-utils", VERSI_TAURI_UTILS)] {
        match versi_di_lock(&isi_lock, nama) {
            Some(v) if v == harap => {}
            Some(v) => {
                eprintln!("Cargo.lock aplikasi memakai {nama} {v}, alat ini dikunci ke {harap}.");
                eprintln!("Perbarui VERSI_* di src/main.rs dan sha256 di siapkan.sh, lalu jalankan ulang.");
                std::process::exit(2);
            }
            None => {
                eprintln!("{nama} tidak ditemukan di {}", lock.display());
                std::process::exit(2);
            }
        }
    }

    let perms_dir = argumen.next().map(PathBuf::from).or_else(permissions_bawaan).unwrap_or_else(|| {
        eprintln!("pakai: scope-bundel [capability.json] [direktori permissions plugin fs]");
        eprintln!("berkas permission belum ada: jalankan ./siapkan.sh lebih dulu");
        std::process::exit(2);
    });

    let mentah = fs::read_to_string(&cap_path).expect("baca capability");
    let dasar: serde_json::Value = serde_json::from_str(&mentah).expect("capability json");

    // Cuma manifest fs yang dimuat di sini, jadi permission plugin lain dibuang
    // supaya ACL-nya bisa resolve. Entri `fs:` tidak disentuh sama sekali.
    let mut bersih = dasar.clone();
    bersih["permissions"]
        .as_array_mut()
        .unwrap()
        .retain(|p| match p {
            serde_json::Value::String(s) => s.starts_with("fs:"),
            serde_json::Value::Object(m) => m
                .get("identifier")
                .and_then(|i| i.as_str())
                .map(|s| s.starts_with("fs:"))
                .unwrap_or(false),
            _ => false,
        });

    let tanpa_default = {
        let mut c = bersih.clone();
        c["permissions"]
            .as_array_mut()
            .unwrap()
            .retain(|p| p.as_str() != Some("fs:default"));
        c
    };

    let tambah_scope = |dasar: &serde_json::Value, pola: &str| {
        let mut c = dasar.clone();
        c["permissions"].as_array_mut().unwrap().push(serde_json::json!({
            "identifier": "fs:scope",
            "allow": [{ "path": pola }]
        }));
        c
    };

    let tambah_izin_mkdir = |dasar: &serde_json::Value| {
        let mut c = dasar.clone();
        c["permissions"]
            .as_array_mut()
            .unwrap()
            .push(serde_json::json!("fs:allow-mkdir"));
        c
    };

    // S7: seluruh blok `fs:scope` dibuang, `fs:default` tetap.
    let tanpa_scope_blok = {
        let mut c = bersih.clone();
        c["permissions"].as_array_mut().unwrap().retain(|p| {
            !(p.get("identifier").and_then(|i| i.as_str()) == Some("fs:scope"))
        });
        c
    };

    // Skenario dan harapannya. Angka `Some(n)` adalah jumlah jalur dari `JALUR`
    // yang lolos. Yang diuji bukan cuma S0, tapi juga bahwa tiap kontrol
    // menghasilkan kebalikannya, karena tanpa itu S0 tidak membuktikan apa pun.
    let s2 = tambah_scope(&bersih, "$APPLOCALDATA/projects/**");
    let s3 = tambah_scope(&bersih, "projects/**");
    let s4 = tambah_scope(&tanpa_default, "$APPLOCALDATA/projects/**");
    let s5 = tambah_scope(&tambah_izin_mkdir(&tanpa_default), "projects/**");
    let s6 = tambah_scope(&tambah_izin_mkdir(&tanpa_default), "$APPLOCALDATA/projects/**");

    let semua = |n: usize| -> Vec<(&'static str, Option<usize>)> {
        PERINTAH.iter().map(|p| (*p, Some(n))).collect()
    };

    let skenario: Vec<(&str, serde_json::Value, Vec<(&'static str, Option<usize>)>)> = vec![
        (
            "S0 capability apa adanya",
            bersih.clone(),
            semua(4),
        ),
        (
            "S1 kontrol: fs:default dibuang",
            tanpa_default.clone(),
            vec![
                ("mkdir", None),
                ("write_file", Some(1)),
                ("write_text_file", Some(1)),
                ("read_file", Some(1)),
                ("read_dir", Some(1)),
                ("remove", Some(1)),
            ],
        ),
        (
            "S2 kontrol: + fs:scope $APPLOCALDATA/projects/**",
            s2,
            semua(4),
        ),
        (
            "S3 kontrol: + fs:scope projects/** (relatif)",
            s3,
            semua(4),
        ),
        (
            "S4 kontrol: fs:default dibuang + $APPLOCALDATA/projects/**",
            s4,
            vec![
                ("mkdir", None),
                ("write_file", Some(3)),
                ("write_text_file", Some(3)),
                ("read_file", Some(3)),
                ("read_dir", Some(3)),
                ("remove", Some(3)),
            ],
        ),
        (
            "S5 kontrol: tanpa fs:default + allow-mkdir + projects/** relatif",
            s5,
            vec![
                ("mkdir", Some(1)),
                ("write_file", Some(1)),
                ("write_text_file", Some(1)),
                ("read_file", Some(1)),
                ("read_dir", Some(1)),
                ("remove", Some(1)),
            ],
        ),
        (
            "S6 kontrol: tanpa fs:default + allow-mkdir + $APPLOCALDATA/projects/**",
            s6,
            vec![
                ("mkdir", Some(3)),
                ("write_file", Some(3)),
                ("write_text_file", Some(3)),
                ("read_file", Some(3)),
                ("read_dir", Some(3)),
                ("remove", Some(3)),
            ],
        ),
        (
            "S7 kontrol: seluruh blok fs:scope dibuang",
            tanpa_scope_blok,
            semua(4),
        ),
    ];

    let mut acl = BTreeMap::new();
    acl.insert("fs".to_string(), muat_manifest(Path::new(&perms_dir)));
    let mut gagal = 0usize;

    for (label, cap, harap) in &skenario {
        let hasil = jalankan(cap, &acl);
        println!("\n### {label}");
        for (perintah, diharap) in harap {
            let dapat = hasil.get(perintah).copied().flatten();
            let tanda = if dapat == *diharap { "ok  " } else { "SALAH" };
            if dapat != *diharap {
                gagal += 1;
            }
            match (dapat, diharap) {
                (Some(n), _) => println!("  {tanda} {perintah:<16} {n}/4 jalur"),
                (None, _) => println!("  {tanda} {perintah:<16} tidak diberikan permission"),
            }
        }
    }

    println!("\n{} skenario, {gagal} hasil tidak sesuai harapan", skenario.len());
    if gagal > 0 {
        std::process::exit(1);
    }
}
